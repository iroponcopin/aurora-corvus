import type { Lang } from "@/lib/wiki-types";

/**
 * Copy that is new in portal 4.0 (the six realms and the controls they brought), in all 13
 * languages. Everything older keeps its original source: the wiki's bundles and copy tables,
 * the Corvus Store jar, or legacy.json. These translations were written for this release and
 * have not yet been read by a native speaker of each language — the same caveat the Store's
 * own release notes make about theirs.
 *
 * `{0}`, `{1}` are positional placeholders.
 */
export interface Fresh {
  heroLine1: string;
  heroLine2: string;
  heroScroll: string;
  sound: string;
  soundOn: string;
  soundOff: string;
  realms: {
    codex: { eyebrow: string; title: string; lede: string; cta: string };
    showroom: { eyebrow: string; title: string; lede: string; cta: string };
    store: { eyebrow: string; title: string; lede: string; cta: string };
    chronology: { eyebrow: string; title: string; lede: string; cta: string; ctaNext: string };
    nexus: { eyebrow: string; title: string; lede: string; cta: string };
  };
  synth: {
    synthesise: string;
    replay: string;
    featured: string;
    fusing: string;
    result: string;
  };
  skin: {
    lighting: string;
    rigs: { studio: string; rim: string; neon: string; dusk: string };
    motion: string;
    idle: string;
    combat: string;
    outerLayer: string;
    resetView: string;
    sealedModel: string;
  };
  store: {
    speed: string;
    timeLeft: string;
    perchDemo: string;
    perchFront: string;
    perchLeave: string;
    perchHidden: string;
    perchShown: string;
    nowPlaying: string;
    installers: string;
  };
  chrono: {
    shipped: string;
    next: string;
    now: string;
    hint: string;
    open: string;
  };
  nexus: {
    terminal: string;
    feeds: string;
    ping: string;
    pinging: string;
    latency: string;
    measured: string;
    unreachable: string;
    copyInvite: string;
    commands: string;
    filter: string;
  };
  debug: { drawCalls: string; fps: string };
  /**
   * The hero's line-up sentence, composed by lib/lineup.ts from what the Store says is out and
   * what is coming. `{0}` is the list of names; `{p}` (Korean) is the topic particle after it.
   * Each pair is [one name, several names]. `join` goes between the sentences.
   */
  lineup: {
    out: [string, string];
    coming: [string, string];
    keeps: string;
    list: { sep: string; last: string; pair: string };
    join: string;
  };
  /** The header's two menus: Models (the six lines) and Updates (changelog, coming next, teasers, skin). */
  nav: {
    models: string;
    updates: string;
    updatesDesc: { changelog: string; upcoming: string; teasers: string; skin: string };
  };
  /** The Teasers page: every advance notice the Coming-next board published, to replay and to read. */
  teasers: {
    title: string;
    description: string;
    lede: string;
    player: string;
    play: string;
    pause: string;
    replay: string;
    playAll: string;
    prev: string;
    next: string;
    read: string;
    hide: string;
    /** `{0}` is a date. */
    announced: string;
    shipped: string;
    onBoard: string;
    releaseNotes: string;
    all: string;
    search: string;
    empty: string;
  };
  /** Sparxie's public preview pictures, shown while the skin itself is sealed. */
  skinPreview: { title: string; note: string; front: string; side: string };
}

